#ifndef _NIXIETUBE_H_
#define _NIXIETUBE_H_

#define SEG		P0
#define	DIG		P2




//数码管初始化，初始化端口，可以调用该函数，或者在GPIO里对端口初始化
extern void NixieTube_init(void);

extern void NixieTube_Clear();

//========================================================================
// 描述: 数码管显示，把显示缓存的数据显示到数码管, 1ms定时器调用
// 参数: 无
// 返回: none.
//========================================================================
extern void NixieTube_Disp(void);


//========================================================================
// 描述: 数码管特定位显示一个数字，不影响其他位.
// 参数: 
//		pos：要显示数字的位，0-7；
//		num：要显示的数字（0-9）；
//		point：(0或者非0),0：小数点不显示；其他：小数点显示
// 返回: none.
//========================================================================
extern void NixieTube_OneDig(unsigned char , unsigned char ,unsigned char );

//========================================================================
// 描述: 数码管显示整数.
// 参数: (-65536~65535).
// 返回: none.
//========================================================================
extern void NixieTube_Int(int );

//========================================================================
// 描述: 数码管显示浮点数.
// 参数: 浮点数num, 精度jingdu(1,2,3,4).
// 返回: none.
//========================================================================
extern void NixieTube_Float(float, unsigned char );

//========================================================================
// 描述: 数码管显示 时-分-秒.
// 参数: BCD码格式的：时  分 秒

// 返回: none.
//========================================================================
extern void NixieTube_Time(unsigned char, unsigned char,unsigned char);


//========================================================================
// 描述: 数码管显示 年-月-日.
// 参数: BCD码格式的：年  月 日

// 返回: none.
//========================================================================
extern void NixieTube_Date(unsigned char, unsigned char,unsigned char);
	

#endif